## ================== PANDAS COMPLETE SUMMARY ==================

import pandas as pd

## -----------------------------------------------------------
## 1. DATAFRAME CREATION
## -----------------------------------------------------------
data = {
    "name": ["Jay", "Rahul", "Aman"],
    "marks": [90, 85, 88]
}

df = pd.DataFrame(data)

## -----------------------------------------------------------
## 2. BASIC INFO
## -----------------------------------------------------------
df.shape        ## (rows, columns)
df.columns      ## column names
df.head()       ## first 5 rows
df.tail()       ## last 5 rows
df.info()       ## data types + info
df.describe()   ## statistics

## -----------------------------------------------------------
## 3. ACCESSING DATA
## -----------------------------------------------------------
df["name"]              ## single column
df[["name","marks"]]    ## multiple columns

df.iloc[0]              ## row by index
df.iloc[0:2]            ## multiple rows

df.loc[0]               ## label-based access

## -----------------------------------------------------------
## 4. ADD / MODIFY COLUMN
## -----------------------------------------------------------
df["grade"] = ["A","B","A"]

df["double"] = df["marks"] * 2

## -----------------------------------------------------------
## 5. FILTERING (VERY IMPORTANT)
## -----------------------------------------------------------
df[df["marks"] > 85]

df[(df["marks"] > 85) & (df["marks"] < 95)]

df[(df["marks"] > 85) | (df["name"] == "Jay")]

## -----------------------------------------------------------
## 6. SORTING
## -----------------------------------------------------------
df.sort_values("marks")

df.sort_values("marks", ascending=False)

## -----------------------------------------------------------
## 7. AGGREGATE FUNCTIONS
## -----------------------------------------------------------
df["marks"].mean()
df["marks"].max()
df["marks"].min()
df["marks"].sum()

## -----------------------------------------------------------
## 8. VALUE COUNTS
## -----------------------------------------------------------
df["marks"].value_counts()

## -----------------------------------------------------------
## 9. GROUPBY (IMPORTANT ⚡)
## -----------------------------------------------------------
df.groupby("name")["marks"].mean()

## -----------------------------------------------------------
## 10. APPLY FUNCTION
## -----------------------------------------------------------
df["marks"].apply(lambda x: x*2)

## -----------------------------------------------------------
## 11. HANDLING MISSING VALUES
## -----------------------------------------------------------
df.isnull()        ## check null
df.dropna()        ## remove null
df.fillna(0)       ## replace null

## -----------------------------------------------------------
## 12. READING FILES (REAL WORLD)
## -----------------------------------------------------------
df = pd.read_csv("file.csv")

df.to_csv("file.csv")

## -----------------------------------------------------------
## 13. INDEX OPERATIONS
## -----------------------------------------------------------
df.set_index("name")

df.reset_index()

## -----------------------------------------------------------
## 14. DROP DATA
## -----------------------------------------------------------
df.drop("marks", axis=1)   ## drop column

df.drop(0, axis=0)         ## drop row

## -----------------------------------------------------------
## 15. RENAME COLUMNS
## -----------------------------------------------------------
df.rename(columns={"marks": "score"})


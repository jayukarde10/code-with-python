## Import
import numpy as np

## -----------------------------------------------------------
## 1. ARRAY CREATION
## -----------------------------------------------------------
np.array([1,2,3])        ## create array
np.zeros(3)              ## [0. 0. 0.]
np.ones(3)               ## [1. 1. 1.]
np.arange(0,10)          ## range (step-based)
np.linspace(0,1,5)       ## equal spacing

## -----------------------------------------------------------
## 2. ARRAY PROPERTIES
## -----------------------------------------------------------
arr.shape     ## (rows, cols)
arr.ndim      ## dimension
arr.size      ## total elements
arr.dtype     ## data type

## -----------------------------------------------------------
## 3. RESHAPING
## -----------------------------------------------------------
arr.reshape(2,3)   ## change shape
arr.flatten()      ## 2D → 1D
arr.T              ## transpose

## -----------------------------------------------------------
## 4. INDEXING & SLICING
## -----------------------------------------------------------
arr[0]             ## first element
arr[1:3]           ## slicing
arr[row, col]      ## 2D access

## -----------------------------------------------------------
## 5. OPERATIONS (ELEMENT-WISE)
## -----------------------------------------------------------
arr + 2
arr * 2
arr1 + arr2
arr1 * arr2

## -----------------------------------------------------------
## 6. AGGREGATE FUNCTIONS
## -----------------------------------------------------------
arr.sum()
arr.mean()
arr.max()
arr.min()

## axis concept:
arr.sum(axis=0)    ## column-wise
arr.sum(axis=1)    ## row-wise

## -----------------------------------------------------------
## 7. BOOLEAN INDEXING (FILTERING)
## -----------------------------------------------------------
arr[arr > 10]      ## filter values

## -----------------------------------------------------------
## 8. WHERE FUNCTION
## -----------------------------------------------------------
np.where(arr > 10)   ## returns index

## -----------------------------------------------------------
## 9. RANDOM
## -----------------------------------------------------------
np.random.rand(3)         ## random floats
np.random.randint(1,10)   ## random integers

## -----------------------------------------------------------
## 10. SORTING & UNIQUE
## -----------------------------------------------------------
np.sort(arr)
np.unique(arr)

## -----------------------------------------------------------
## 11. STACKING
## -----------------------------------------------------------
np.vstack([a,b])    ## vertical
np.hstack([a,b])    ## horizontal

## -----------------------------------------------------------
## 12. REPEAT / TILE
## -----------------------------------------------------------
np.tile(arr, (3,1))   ## repeat rows

## -----------------------------------------------------------
## 13. COPY vs VIEW
## -----------------------------------------------------------
b = arr          ## view (linked)
b = arr.copy()   ## separate copy

## -----------------------------------------------------------
## 14. FANCY INDEXING
## -----------------------------------------------------------
arr[[0,2]]       ## multiple indexes

## -----------------------------------------------------------
## 15. DIAGONAL
## -----------------------------------------------------------
arr.diagonal()
np.diag(arr)

